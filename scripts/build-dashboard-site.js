#!/usr/bin/env node
/** Assemble the self-contained GitHub Pages payload for Unit 15d. */
const fs = require('node:fs');
const path = require('node:path');
const { nav } = require('./lib/reportPage.js');

const SITE = path.join('reports', 'site');

const NAV_STYLE = `
  .sitenav { display: flex; flex-wrap: wrap; gap: 4px; max-width: 1060px; margin: 0 auto 20px;
             background: #fff; border: 1px solid var(--hair); border-radius: 10px; padding: 6px; }
  .navlink { padding: 7px 14px; border-radius: 7px; font-size: 13.5px; font-weight: 600;
             text-decoration: none; color: var(--soft); }
  .navlink:hover { background: #f3f6f9; color: var(--ink); }
  .navlink.here { background: var(--ink); color: #fff; }
`;

function copyIfPresent(source, destination) {
  if (!fs.existsSync(source)) return false;
  fs.cpSync(source, destination, { recursive: true });
  return true;
}

/**
 * The dashboard is generated by its own script and knows nothing about the
 * other pages, so the shared nav is stitched on at publish time. Without it the
 * dashboard is a dead end.
 */
function addSiteNav(indexFile) {
  const html = fs.readFileSync(indexFile, 'utf8');
  if (html.includes('class="sitenav"')) return;
  fs.writeFileSync(
    indexFile,
    html.replace('</style>', `${NAV_STYLE}</style>`).replace('<main>', `${nav('index.html')}\n<main>`),
  );
}

function main() {
  fs.rmSync(SITE, { recursive: true, force: true });
  fs.mkdirSync(SITE, { recursive: true });

  const required = [
    [path.join('reports', 'dashboard.html'), path.join(SITE, 'index.html')],
    [path.join('reports', 'metrics.json'), path.join(SITE, 'metrics.json')],
    [path.join('reports', 'history.json'), path.join(SITE, 'history.json')],
  ];
  for (const [source, destination] of required) {
    if (!copyIfPresent(source, destination)) {
      throw new Error(`Cannot publish dashboard: ${source} is missing.`);
    }
  }

  // The traceability pages are generated separately and are not worth failing
  // the publish over: the dashboard alone is still a truthful page.
  const optional = [
    'coverage.html',
    'traceability.html',
    'gates.html',
    'endpoints.html',
    'summary.json',
    'traceability.json',
  ];
  for (const file of optional) {
    if (!copyIfPresent(path.join('reports', file), path.join(SITE, file))) {
      console.warn(`${file} missing; publishing without it. Run \`npm run report:pages\` first.`);
    }
  }
  addSiteNav(path.join(SITE, 'index.html'));

  const allureDestination = path.join(SITE, 'allure');
  if (!copyIfPresent('allure-report', allureDestination)) {
    fs.mkdirSync(allureDestination, { recursive: true });
    fs.writeFileSync(
      path.join(allureDestination, 'index.html'),
      '<!doctype html><meta charset="utf-8"><title>Detailed test evidence unavailable</title>' +
        '<h1>Detailed test evidence unavailable</h1>' +
        '<p>The dashboard is current, but detailed evidence could not be generated for this run.</p>',
    );
    console.warn('Allure report missing; published an honest unavailable page.');
  }
  console.log(`dashboard site assembled at ${SITE}`);
}

if (require.main === module) main();

module.exports = { copyIfPresent, addSiteNav };
