#!/usr/bin/env node
/**
 * Scores docs/surface-inventory.json and writes the human report.
 * Coverage % is (covered + bug + 0.5*partial) / in-scope items.
 * Excluded nav areas are signed-off and stay out of the denominator.
 */
const fs = require('node:fs');
const path = require('node:path');

const SOURCE = path.join('docs', 'surface-inventory.json');
const MARKDOWN = path.join('docs', 'surface-inventory.md');
const SNAPSHOT = path.join('reports', 'coverage-percent.json');

const SCORE = { covered: 1, bug: 1, partial: 0.5, wip: 0, gap: 0 };

function loadInventory() {
  return JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
}

function summarize(inventory) {
  const inScope = inventory.items.filter((item) => item.status !== 'excluded');
  const byStatus = {};
  const byKind = {};
  let score = 0;
  for (const item of inScope) {
    byStatus[item.status] = (byStatus[item.status] ?? 0) + 1;
    byKind[item.kind] = byKind[item.kind] ?? { n: 0, score: 0 };
    byKind[item.kind].n += 1;
    const add = SCORE[item.status] ?? 0;
    byKind[item.kind].score += add;
    score += add;
  }
  const percent = inScope.length ? Math.round((score / inScope.length) * 1000) / 10 : 0;
  const gaps = inScope
    .filter((item) => item.status === 'gap' || item.status === 'wip' || item.status === 'partial')
    .sort((a, b) => riskRank(a.risk) - riskRank(b.risk) || a.id.localeCompare(b.id));
  const bugs = inScope.filter((item) => item.status === 'bug');
  return {
    asOf: inventory.asOf,
    total: inventory.items.length,
    inScope: inScope.length,
    excluded: inventory.items.length - inScope.length,
    score,
    percent,
    byStatus,
    byKind,
    gaps,
    bugs,
  };
}

function riskRank(risk) {
  return { P0: 0, P1: 1, P2: 2, P3: 3 }[risk] ?? 9;
}

function statusMark(status) {
  return (
    {
      covered: '✅ covered',
      bug: '🐞 @bug',
      partial: '◐ partial',
      wip: '☐ wip',
      gap: '❌ gap',
      excluded: '➖ excluded',
    }[status] ?? status
  );
}

function render(inventory, stats) {
  const kinds = ['route', 'endpoint', 'action', 'state'];
  const lines = [];
  lines.push('# Surface inventory — Rethink Clinical');
  lines.push('');
  lines.push(
    `Source of truth: [\`surface-inventory.json\`](./surface-inventory.json). Regenerated by \`npm run coverage:inventory\` and at the end of every Cucumber run.`,
  );
  lines.push('');
  lines.push(`**As of:** ${stats.asOf}`);
  lines.push('');
  lines.push(`## Coverage ${stats.percent}%`);
  lines.push('');
  lines.push(
    `${stats.percent}% of the **in-scope** surface is covered (full credit for \`covered\` and \`@bug\`, half credit for \`partial\`). ${stats.inScope} in-scope items, ${stats.excluded} signed-off exclusion${stats.excluded === 1 ? '' : 's'}.`,
  );
  lines.push('');
  lines.push('| Status | Count |');
  lines.push('|--------|------:|');
  for (const status of ['covered', 'bug', 'partial', 'wip', 'gap']) {
    lines.push(`| ${statusMark(status)} | ${stats.byStatus[status] ?? 0} |`);
  }
  lines.push(`| excluded (not in %) | ${stats.excluded} |`);
  lines.push('');
  lines.push('| Kind | Items | Weighted coverage |');
  lines.push('|------|------:|------------------:|');
  for (const kind of kinds) {
    const row = stats.byKind[kind] ?? { n: 0, score: 0 };
    const pct = row.n ? Math.round((row.score / row.n) * 1000) / 10 : 0;
    lines.push(`| ${kind} | ${row.n} | ${pct}% |`);
  }
  lines.push('');
  lines.push('## Ranked gap backlog');
  lines.push('');
  lines.push('Close these in Unit 9 (states), Unit 10 (Analyze Data breadth), and Unit 11 (writes).');
  lines.push('');
  lines.push('| Risk | ID | Surface | Status | Why it is open | Next unit |');
  lines.push('|------|----|---------|--------|----------------|-----------|');
  for (const item of stats.gaps) {
    lines.push(
      `| ${item.risk} | \`${item.id}\` | ${item.surface} | ${statusMark(item.status)} | ${item.gap ?? '—'} | ${nextUnit(item)} |`,
    );
  }
  lines.push('');
  lines.push('## Known defects (count as covered for %; still red in `-p bugs`)');
  lines.push('');
  lines.push('| Risk | ID | Surface | Tests |');
  lines.push('|------|----|---------|-------|');
  for (const item of stats.bugs) {
    lines.push(
      `| ${item.risk} | \`${item.id}\` | ${item.surface} | ${(item.tests ?? []).join(', ')} |`,
    );
  }
  lines.push('');
  lines.push('## Full inventory');
  lines.push('');
  for (const kind of kinds) {
    lines.push(`### ${kind[0].toUpperCase()}${kind.slice(1)}s`);
    lines.push('');
    lines.push('| ID | Surface | Status | Risk | Tests |');
    lines.push('|----|---------|--------|------|-------|');
    for (const item of inventory.items.filter((row) => row.kind === kind)) {
      lines.push(
        `| \`${item.id}\` | ${item.surface} | ${statusMark(item.status)} | ${item.risk} | ${(item.tests ?? []).join(', ') || '—'} |`,
      );
    }
    lines.push('');
  }
  lines.push('## How the percentage is computed');
  lines.push('');
  lines.push('- **Denominator:** every item except `excluded`.');
  lines.push('- **Numerator:** `covered` and `bug` = 1, `partial` = 0.5, `wip` and `gap` = 0.');
  lines.push('- Coverage must not drop. Unit 14 will ratchet this number in CI.');
  lines.push('');
  return `${lines.join('\n')}\n`;
}

function nextUnit(item) {
  if (item.id.startsWith('S-') || item.id === 'R-sessions-new') return 'Unit 9/10';
  if (item.id.startsWith('A-print') || item.id === 'A-scope-select' || item.id === 'S-analyze-loading') {
    return 'Unit 10';
  }
  if (item.id.startsWith('A-confirm') || item.id.startsWith('A-dismiss') || item.id === 'A-record-data') {
    return 'Unit 11';
  }
  return 'Unit 9';
}

function writeSurfaceInventoryReport() {
  const inventory = loadInventory();
  const stats = summarize(inventory);
  fs.mkdirSync('docs', { recursive: true });
  fs.mkdirSync('reports', { recursive: true });
  fs.writeFileSync(MARKDOWN, render(inventory, stats));
  fs.writeFileSync(
    SNAPSHOT,
    `${JSON.stringify(
      {
        percent: stats.percent,
        inScope: stats.inScope,
        covered: stats.byStatus.covered ?? 0,
        bug: stats.byStatus.bug ?? 0,
        partial: stats.byStatus.partial ?? 0,
        wip: stats.byStatus.wip ?? 0,
        gap: stats.byStatus.gap ?? 0,
        asOf: stats.asOf,
      },
      null,
      2,
    )}\n`,
  );
  return [MARKDOWN, SNAPSHOT, `${stats.percent}%`];
}

if (require.main === module) {
  const written = writeSurfaceInventoryReport();
  console.log(`coverage  ${written.join(' · ')}`);
}

module.exports = { loadInventory, summarize, writeSurfaceInventoryReport };
